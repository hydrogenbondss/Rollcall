export function getRegion(country: string): string {
  const east = ['Japan', 'South Korea', 'China', 'Hong Kong', 'Taiwan', 'Mongolia']
  const southeast = ['Singapore', 'Malaysia', 'Thailand', 'Philippines', 'Indonesia', 'Vietnam', 'Cambodia', 'Laos', 'Brunei', 'Myanmar']
  const south = ['India', 'Bangladesh', 'Pakistan', 'Nepal', 'Sri Lanka']
  if (east.includes(country)) return 'East Asia'
  if (southeast.includes(country)) return 'Southeast Asia'
  if (south.includes(country)) return 'South Asia'
  return ''
}

export function getRegionColor(country: string): string {
  const region = getRegion(country)
  if (region === 'East Asia') return '#c4728e'
  if (region === 'Southeast Asia') return '#228b68'
  if (region === 'South Asia') return '#c85a32'
  return '#b0a89e'
}

